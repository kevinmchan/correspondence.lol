-- Push notifications: tell room members when a game starts or when it is their
-- turn, even if the app is closed.
--
-- Browsers register a push subscription against their device token. When
-- something happens, the database works out who to tell (everyone in the room
-- except whoever did it and whoever has the room open right now) and hands
-- the list to the `push` edge function, which only does the sending.
--
-- Secrets never leave the server side: a random shared secret and the VAPID
-- signing keys live in rooms.settings, which no API role can read. The signing
-- keys are generated by the edge function itself (push_init) the first time.

create extension if not exists pg_net with schema extensions;

alter table rooms.members add column seen_at timestamptz; -- last time this member had the room open

create table rooms.settings (
  key text primary key,
  value text not null
);

create table rooms.push_subscriptions (
  endpoint text primary key,
  token_hash text not null,
  p256dh text not null check (char_length(p256dh) between 20 and 200),
  auth text not null check (char_length(auth) between 8 and 100),
  created_at timestamptz not null default now(),
  gone_at timestamptz -- set when the device unsubscribes or the push service reports it gone
);

create index push_subscriptions_token_idx on rooms.push_subscriptions (token_hash);

alter table rooms.settings enable row level security;
alter table rooms.push_subscriptions enable row level security;
revoke all on rooms.settings, rooms.push_subscriptions from public, anon, authenticated;

insert into rooms.settings (key, value) values
  ('push_secret', encode(extensions.gen_random_bytes(24), 'hex')),
  ('push_url', 'https://ukhofpgksjdeypebvvhd.supabase.co/functions/v1/push')
on conflict (key) do nothing;

create function rooms.setting(p_key text) returns text
language sql stable set search_path = '' as $$
  select value from rooms.settings where key = p_key;
$$;

-- Queue a notification for everyone in a room except p_actor and anyone who
-- has the room open. Never raises: notifying is best effort.
create function rooms.notify(p_room uuid, p_actor smallint, p_body text, p_url text, p_tag text) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_subs jsonb;
begin
  select jsonb_agg(jsonb_build_object('endpoint', s.endpoint, 'p256dh', s.p256dh, 'auth', s.auth))
  into v_subs
  from rooms.members m
  join rooms.push_subscriptions s on s.token_hash = m.token_hash and s.gone_at is null
  where m.room_id = p_room
    and m.seat is distinct from p_actor
    and (m.seen_at is null or m.seen_at < now() - interval '45 seconds');
  if v_subs is null or rooms.setting('vapid_private') is null then
    return;
  end if;
  perform net.http_post(
    url := rooms.setting('push_url'),
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-push-secret', rooms.setting('push_secret')),
    body := jsonb_build_object(
      'vapid', jsonb_build_object(
        'public', rooms.setting('vapid_public'),
        'private', rooms.setting('vapid_private'),
        'subject', 'https://correspondence.lol'),
      'subscriptions', v_subs,
      'payload', jsonb_build_object(
        'title', (select name from rooms.rooms where id = p_room),
        'body', p_body, 'url', p_url, 'tag', p_tag)));
exception when others then
  null;
end;
$$;

revoke execute on function rooms.setting(text) from public, anon, authenticated;
revoke execute on function rooms.notify(uuid, smallint, text, text, text) from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- Public API for browsers
-- ---------------------------------------------------------------------------

-- The key browsers subscribe with (null until push is set up).
create function public.push_key() returns text
language sql stable security definer set search_path = '' as $$
  select rooms.setting('vapid_public');
$$;

-- Register this device for notifications. Only real push services are accepted
-- as endpoints, since the server will be sending requests to them.
create function public.push_subscribe(p_token text, p_endpoint text, p_p256dh text, p_auth text) returns void
language plpgsql security definer set search_path = '' as $$
begin
  perform rooms.check_token(p_token);
  if p_endpoint is null or char_length(p_endpoint) > 1000 or p_endpoint !~
     '^https://(fcm\.googleapis\.com|updates\.push\.services\.mozilla\.com|[a-z0-9.-]+\.push\.apple\.com|[a-z0-9.-]+\.notify\.windows\.com)/' then
    raise exception 'This browser''s notification service is not supported.' using errcode = '22023';
  end if;
  insert into rooms.push_subscriptions (endpoint, token_hash, p256dh, auth)
  values (p_endpoint, rooms.token_hash(p_token), p_p256dh, p_auth)
  on conflict (endpoint) do update
    set token_hash = excluded.token_hash, p256dh = excluded.p256dh, auth = excluded.auth, gone_at = null;
end;
$$;

create function public.push_unsubscribe(p_token text, p_endpoint text) returns void
language sql security definer set search_path = '' as $$
  update rooms.push_subscriptions set gone_at = now()
  where endpoint = p_endpoint and token_hash = rooms.token_hash(p_token);
$$;

-- Pages call this while a room or one of its games is on screen (and with
-- p_here false when it stops being), so people are not notified about things
-- they are watching happen.
create function public.room_seen(p_room uuid, p_token text, p_here boolean default true) returns void
language sql security definer set search_path = '' as $$
  update rooms.members
  set seen_at = case when p_here then now() end
  where room_id = p_room and token_hash = rooms.token_hash(p_token);
$$;

-- ---------------------------------------------------------------------------
-- Public API for the push edge function, guarded by the shared secret
-- ---------------------------------------------------------------------------

create function public.push_check(p_secret text) returns boolean
language sql stable security definer set search_path = '' as $$
  select p_secret is not null and p_secret = rooms.setting('push_secret');
$$;

-- Store freshly generated signing keys, once. Returns the public key in use.
create function public.push_init(p_secret text, p_public text, p_private text) returns text
language plpgsql security definer set search_path = '' as $$
begin
  if not public.push_check(p_secret) then
    raise exception 'Not allowed.' using errcode = '42501';
  end if;
  if rooms.setting('vapid_private') is null then
    insert into rooms.settings (key, value) values ('vapid_public', p_public), ('vapid_private', p_private);
  end if;
  return rooms.setting('vapid_public');
end;
$$;

-- Retire subscriptions the push service says no longer exist.
create function public.push_gone(p_secret text, p_endpoints text[]) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not public.push_check(p_secret) then
    raise exception 'Not allowed.' using errcode = '42501';
  end if;
  update rooms.push_subscriptions set gone_at = now() where endpoint = any (p_endpoints);
end;
$$;

