-- A move was made: it is now everyone else's turn.
create function postmarks.notify_turn() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_actor smallint := (new.last->>'player')::smallint;
begin
  if new.moves > old.moves and new.status = 'playing' then
    perform rooms.notify(
      new.room_id, v_actor,
      coalesce((select name from rooms.members where room_id = new.room_id and seat = v_actor), 'Someone')
        || ' moved in Postmarks. Your turn!',
      '/postmarks/?game=' || new.id, 'game:' || new.id);
  end if;
  return null;
end;
$$;

revoke execute on function postmarks.notify_turn() from public, anon, authenticated;

create trigger notify_turn after update on postmarks.games
  for each row execute function postmarks.notify_turn();

-- A game was started: tell the rest of the room. (Same as before, plus the
-- rooms.notify call.)
create or replace function public.postmarks_create(
  p_room uuid, p_token text, p_size integer, p_regions integer[], p_solution integer[]
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_seat smallint := rooms.seat(p_room, p_token);
  v_name text;
  g postmarks.games;
begin
  if v_seat is null then
    raise exception 'Join the room to start a game.' using errcode = 'P0001';
  end if;
  if p_size is null or p_size < 5 or p_size > 9 then
    raise exception 'Grid size must be 5 to 9.' using errcode = '22023';
  end if;
  if coalesce(array_length(p_regions, 1), 0) <> p_size * p_size
     or coalesce(array_length(p_solution, 1), 0) <> p_size
     or exists (select 1 from unnest(p_regions) r where r is null or r < 0 or r >= p_size)
     or exists (select 1 from unnest(p_solution) s where s is null or s < 0 or s >= p_size)
     or (select count(distinct s) from unnest(p_solution) s) <> p_size
     or (select count(distinct p_regions[(t.ord - 1) * p_size + t.col + 1])
         from unnest(p_solution) with ordinality as t(col, ord)) <> p_size then
    raise exception 'That is not a valid puzzle.' using errcode = '22023';
  end if;

  insert into postmarks.games (room_id, size, regions, solution, cells)
  values (p_room, p_size, p_regions::smallint[], p_solution::smallint[],
          array_fill(0::smallint, array[p_size * p_size]))
  returning * into g;
  select m.name into v_name from rooms.members m where m.room_id = p_room and m.seat = v_seat;
  perform rooms.announce(
    p_room, v_name || ' started a ' || p_size || ' × ' || p_size || ' game of Postmarks', 'postmarks', g.id);
  perform rooms.notify(
    p_room, v_seat, v_name || ' started a game of Postmarks', '/postmarks/?game=' || g.id, 'game:' || g.id);
  return postmarks.game_view(g, v_seat);
end;
$$;

